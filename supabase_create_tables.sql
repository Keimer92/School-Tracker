-- ============================================
-- CREACIÓN DE TABLAS FALTANTES EN SUPABASE
-- ============================================

-- 1. Tabla grado_asignatura (relación muchos a muchos)
CREATE TABLE IF NOT EXISTS public.grado_asignatura (
    grado_id BIGINT NOT NULL,
    asignatura_id BIGINT NOT NULL,
    user_id UUID REFERENCES auth.users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    PRIMARY KEY (grado_id, asignatura_id, user_id),
    CONSTRAINT grado_asignatura_grado_id_fkey FOREIGN KEY (grado_id) REFERENCES public.grado(id) ON DELETE CASCADE,
    CONSTRAINT grado_asignatura_asignatura_id_fkey FOREIGN KEY (asignatura_id) REFERENCES public.asignatura(id) ON DELETE CASCADE,
    CONSTRAINT grado_asignatura_grado_id_asignatura_id_user_id_key UNIQUE (grado_id, asignatura_id, user_id)
);

-- 2. Tabla colegio_asignatura (relación muchos a muchos)
CREATE TABLE IF NOT EXISTS public.colegio_asignatura (
    colegio_id BIGINT NOT NULL,
    asignatura_id BIGINT NOT NULL,
    user_id UUID REFERENCES auth.users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    PRIMARY KEY (colegio_id, asignatura_id, user_id),
    CONSTRAINT colegio_asignatura_colegio_id_fkey FOREIGN KEY (colegio_id) REFERENCES public.colegio(id) ON DELETE CASCADE,
    CONSTRAINT colegio_asignatura_asignatura_id_fkey FOREIGN KEY (asignatura_id) REFERENCES public.asignatura(id) ON DELETE CASCADE,
    CONSTRAINT colegio_asignatura_colegio_id_asignatura_id_user_id_key UNIQUE (colegio_id, asignatura_id, user_id)
);

-- 3. Tabla configuracion_calificacion (configuración de notas)
CREATE TABLE IF NOT EXISTS public.configuracion_calificacion (
    id TEXT PRIMARY KEY,
    nombre TEXT NOT NULL,
    color TEXT NOT NULL,
    minimo INTEGER NOT NULL DEFAULT 0,
    user_id UUID REFERENCES auth.users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Tabla colegio_dias_asistencia (días de asistencia por colegio)
CREATE TABLE IF NOT EXISTS public.colegio_dias_asistencia (
    colegio_id BIGINT PRIMARY KEY,
    lunes BOOLEAN DEFAULT TRUE,
    martes BOOLEAN DEFAULT TRUE,
    miercoles BOOLEAN DEFAULT TRUE,
    jueves BOOLEAN DEFAULT TRUE,
    viernes BOOLEAN DEFAULT TRUE,
    sabado BOOLEAN DEFAULT TRUE,
    domingo BOOLEAN DEFAULT TRUE,
    user_id UUID REFERENCES auth.users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT colegio_dias_asistencia_colegio_id_fkey FOREIGN KEY (colegio_id) REFERENCES public.colegio(id) ON DELETE CASCADE
);

-- 5. Tablas de sincronización (pendiente de deletions)
CREATE TABLE IF NOT EXISTS public.sync_pending_deletions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla TEXT NOT NULL,
    registro_id BIGINT NOT NULL,
    user_id UUID REFERENCES auth.users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.sync_pending_deletions_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL,
    fecha TEXT NOT NULL,
    user_id UUID REFERENCES auth.users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.sync_pending_deletions_nota (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL,
    criterio_id BIGINT NOT NULL,
    corte_evaluativo_id BIGINT NOT NULL,
    asignatura_id BIGINT NOT NULL,
    user_id UUID REFERENCES auth.users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.sync_pending_deletions_grado_asignatura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grado_id BIGINT NOT NULL,
    asignatura_id BIGINT NOT NULL,
    user_id UUID REFERENCES auth.users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.sync_pending_deletions_colegio_asignatura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colegio_id BIGINT NOT NULL,
    asignatura_id BIGINT NOT NULL,
    user_id UUID REFERENCES auth.users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

